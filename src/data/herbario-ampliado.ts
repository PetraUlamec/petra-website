import type { Plant, FormaPlanta } from '@/lib/types';

type Entry = [string, string, string, FormaPlanta?, string?, string?];
function group(grupo: string, forma: FormaPlanta, color: string, color2: string, entries: Entry[]): Plant[] {
  return entries.map(([nombre, en, sl, visual = forma, primary = color, secondary = color2]) => ({
    id: `herbario-${nombre.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/-$/, '')}`,
    nombre, nombres: { en, sl }, grupo, latin: '', forma: visual, color: primary, color2: secondary,
  }));
}

